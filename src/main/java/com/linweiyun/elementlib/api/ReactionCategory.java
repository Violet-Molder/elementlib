package com.linweiyun.elementlib.api;

/**
 * 元素反应的分类。
 */
public enum ReactionCategory {
    /** 增幅反应（融化 / 蒸发）。 */
    AMPLIFYING,
    /** 剧变反应（超导 / 扩散 / 感电等）。 */
    TRANSFORMATIVE,
    /** 特殊反应（冻结 / 碎冰 / 结晶）。 */
    SPECIAL,
    /** 星体系分支。 */
    STELLAR,
    /** 月体系分支。 */
    LUNAR,
    /** 其它。 */
    OTHER
}
